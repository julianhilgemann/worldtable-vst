#!/usr/bin/env python3
"""Generate parameter code from spec/parameters.yaml (the single source of truth).

Outputs (never hand-edit them):
  source/params/Params.h    ID constants, choice enums, ParamPointers, createLayout()
  source/params/Params.cpp  createLayout() implementation
  source/ui/params.js       metadata for the WebView UI (also used by its mock mode)

Usage:
  tools/gen_params.py           write the files
  tools/gen_params.py --check   exit 1 if the files are out of date (for CI)
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec" / "parameters.yaml"
OUT_H = ROOT / "source" / "params" / "Params.h"
OUT_CPP = ROOT / "source" / "params" / "Params.cpp"
OUT_JS = ROOT / "source" / "ui" / "params.js"

HEADER = "// GENERATED by tools/gen_params.py from spec/parameters.yaml. Do not edit.\n"
ID_RE = re.compile(r"^[a-z][a-z0-9_]*$")


class SpecError(Exception):
    pass


def expand(spec: dict) -> list[dict]:
    params: list[dict] = []
    for group, body in spec["groups"].items():
        if isinstance(body, dict) and "template" in body:
            count = int(body["count"])
            for n in range(1, count + 1):
                for tmpl in body["template"]:
                    p = {}
                    for key, value in tmpl.items():
                        if isinstance(value, str):
                            value = value.replace("{n}", str(n))
                        elif key == "default" and isinstance(value, list):
                            if len(value) != count:
                                raise SpecError(f"{tmpl['id']}: default list needs {count} entries")
                            value = value[n - 1]
                        p[key] = value
                    p["group"] = group
                    p["enum"] = pascal(tmpl["id"].replace("{n}", ""))
                    params.append(p)
        else:
            for item in body:
                p = dict(item)
                p["group"] = group
                p["enum"] = pascal(p["id"])
                params.append(p)
    validate(params)
    return params


def pascal(ident: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[_\W]+", ident) if part)


def enumerator(choice: str) -> str:
    cleaned = choice.replace("#", "Sharp").replace("&", "And")
    cleaned = re.sub(r"[^A-Za-z0-9/ ]", "", cleaned)
    cleaned = cleaned.replace("/", "_")
    words = [w for w in cleaned.split(" ") if w]
    name = "".join(w[0].upper() + w[1:] for w in words)
    return "k" + name


def skew_for(p: dict) -> float:
    if "mid" in p:
        lo, hi, mid = float(p["min"]), float(p["max"]), float(p["mid"])
        if not lo < mid < hi:
            raise SpecError(f"{p['id']}: mid must lie strictly inside (min, max)")
        return math.log(0.5) / math.log((mid - lo) / (hi - lo))
    return float(p.get("skew", 1.0))


def validate(params: list[dict]) -> None:
    seen = set()
    for p in params:
        pid = p.get("id", "")
        if not ID_RE.match(pid):
            raise SpecError(f"bad id '{pid}'")
        if pid in seen:
            raise SpecError(f"duplicate id '{pid}'")
        seen.add(pid)
        t = p.get("type")
        if t == "float":
            lo, hi, d = float(p["min"]), float(p["max"]), float(p["default"])
            if not lo <= d <= hi:
                raise SpecError(f"{pid}: default {d} outside [{lo}, {hi}]")
        elif t == "int":
            lo, hi, d = int(p["min"]), int(p["max"]), int(p["default"])
            if not lo <= d <= hi:
                raise SpecError(f"{pid}: default {d} outside [{lo}, {hi}]")
        elif t == "choice":
            if p["default"] not in p["choices"]:
                raise SpecError(f"{pid}: default '{p['default']}' not in choices")
            names = [enumerator(c) for c in p["choices"]]
            if len(set(names)) != len(names):
                raise SpecError(f"{pid}: choices collide after sanitising: {names}")
        elif t == "bool":
            if not isinstance(p["default"], bool):
                raise SpecError(f"{pid}: bool default must be true/false")
        else:
            raise SpecError(f"{pid}: unknown type '{t}'")


def cpp_float(x: float) -> str:
    s = repr(float(x))
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def cpp_str(s: str) -> str:
    """C++ expression for a juce::String. Non-ASCII text goes through String::fromUTF8
    with octal escapes (juce::String asserts on non-ASCII char* literals)."""
    if s.isascii():
        return json.dumps(s)
    escaped = "".join(
        ch if ch.isascii() and ch not in '"\\' else
        ("\\" + ch if ch in '"\\' else "".join(f"\\{b:03o}" for b in ch.encode("utf-8")))
        for ch in s)
    return f'String::fromUTF8 ("{escaped}")'


def gen_header(params: list[dict]) -> str:
    out = [HEADER, "#pragma once\n", "#include <juce_audio_processors/juce_audio_processors.h>\n",
           "namespace worldtable::params\n{\n",
           "/** Parameter IDs. Permanent once released (DAW sessions depend on them). */",
           "namespace id\n{"]
    for p in params:
        out.append(f"    inline constexpr const char* {p['id']} = \"{p['id']}\";")
    out.append("} // namespace id\n")

    out.append("/** Choice indices, in the order of spec/parameters.yaml. Use as e.g. FltType::kLP24. */")
    done = set()
    for p in params:
        if p["type"] != "choice" or p["enum"] in done:
            continue
        done.add(p["enum"])
        items = ", ".join(f"{enumerator(c)} = {i}" for i, c in enumerate(p["choices"]))
        out.append(f"struct {p['enum']} {{ enum : int {{ {items}, kCount = {len(p['choices'])} }}; }};")
    out.append("")

    out.append("/** Raw value pointers into the APVTS, for lock-free reads on the audio thread. */")
    out.append("struct ParamPointers\n{")
    for p in params:
        out.append(f"    std::atomic<float>* {p['id']} = nullptr;")
    out.append("\n    void bind (juce::AudioProcessorValueTreeState&);")
    out.append("};\n")
    out.append(f"inline constexpr int kNumParameters = {len(params)};\n")
    out.append("juce::AudioProcessorValueTreeState::ParameterLayout createLayout();\n")
    out.append("} // namespace worldtable::params\n")
    return "\n".join(out)


def gen_cpp(params: list[dict]) -> str:
    out = [HEADER, '#include "Params.h"\n', "namespace worldtable::params\n{\n",
           "void ParamPointers::bind (juce::AudioProcessorValueTreeState& apvts)\n{"]
    for p in params:
        out.append(f"    {p['id']} = apvts.getRawParameterValue (id::{p['id']});")
        out.append(f"    jassert ({p['id']} != nullptr);")
    out.append("}\n")

    out.append("juce::AudioProcessorValueTreeState::ParameterLayout createLayout()\n{")
    out.append("    using namespace juce;")
    out.append("    AudioProcessorValueTreeState::ParameterLayout layout;\n")
    for p in params:
        pid = f"ParameterID {{ id::{p['id']}, 1 }}"
        name = cpp_str(p["name"])
        t = p["type"]
        if t == "float":
            step = cpp_float(p.get("step", 0.0))
            rng = (f"NormalisableRange<float> ({cpp_float(p['min'])}, {cpp_float(p['max'])}, {step}, "
                   f"{cpp_float(skew_for(p))})")
            attrs = f"AudioParameterFloatAttributes().withLabel ({cpp_str(p.get('unit', ''))})"
            out.append(f"    layout.add (std::make_unique<AudioParameterFloat> ({pid}, {name},\n"
                       f"        {rng}, {cpp_float(p['default'])}, {attrs}));")
        elif t == "int":
            attrs = f"AudioParameterIntAttributes().withLabel ({cpp_str(p.get('unit', ''))})"
            out.append(f"    layout.add (std::make_unique<AudioParameterInt> ({pid}, {name}, "
                       f"{int(p['min'])}, {int(p['max'])}, {int(p['default'])}, {attrs}));")
        elif t == "choice":
            choices = ", ".join(cpp_str(c) for c in p["choices"])
            idx = p["choices"].index(p["default"])
            out.append(f"    layout.add (std::make_unique<AudioParameterChoice> ({pid}, {name},\n"
                       f"        StringArray {{ {choices} }}, {idx}));")
        elif t == "bool":
            out.append(f"    layout.add (std::make_unique<AudioParameterBool> ({pid}, {name}, "
                       f"{'true' if p['default'] else 'false'}));")
    out.append("\n    return layout;\n}\n")
    out.append("} // namespace worldtable::params\n")
    return "\n".join(out)


def gen_js(params: list[dict]) -> str:
    meta = {}
    for p in params:
        m = {"name": p["name"], "type": p["type"], "group": p["group"]}
        if p["type"] in ("float", "int"):
            m.update(min=p["min"], max=p["max"], default=p["default"])
            if p["type"] == "float":
                m["skew"] = round(skew_for(p), 9)
                if "step" in p:
                    m["step"] = p["step"]
        elif p["type"] == "choice":
            m.update(choices=p["choices"], default=p["choices"].index(p["default"]))
        elif p["type"] == "bool":
            m["default"] = bool(p["default"])
        if p.get("unit"):
            m["unit"] = p["unit"]
        if p.get("rebuild"):
            m["rebuild"] = True
        meta[p["id"]] = m
    body = json.dumps(meta, indent=2, ensure_ascii=False)
    return HEADER + "window.WT_PARAMS = " + body + ";\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args()

    try:
        params = expand(yaml.safe_load(SPEC.read_text(encoding="utf-8")))
    except SpecError as e:
        print(f"parameters.yaml: {e}", file=sys.stderr)
        return 2

    outputs = {OUT_H: gen_header(params), OUT_CPP: gen_cpp(params), OUT_JS: gen_js(params)}

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0

    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"{len(params)} parameters -> " + ", ".join(str(p.relative_to(ROOT)) for p in outputs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
